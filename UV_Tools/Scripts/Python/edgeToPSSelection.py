class PhotoshopCommunicator(object):
    """Handles the generation and execution of the JSX script for Photoshop."""

    def __init__(self, photoshop_path):
        if not photoshop_path or not os.path.exists(photoshop_path):
            raise ValueError("Photoshop path is invalid or not set.")
        self.photoshop_path = photoshop_path
        self.temp_jsx_file = os.path.join(tempfile.gettempdir(), "maya_to_ps_temp.jsx")

    def execute(self, path_data, make_selection_only, expand_texels):
        """Generates and executes the JSX script."""
        jsx_script = self._generate_jsx(path_data, make_selection_only, expand_texels)
        self._write_jsx_file(jsx_script)
        self._run_photoshop_with_script()

    def _write_jsx_file(self, content):
        """Writes the generated JSX content to a temporary file."""
        try:
            with open(self.temp_jsx_file, "w") as f:
                f.write(content)
        except IOError as e:
            raise IOError("Failed to write temporary JSX file: {0}".format(e))

    def _run_photoshop_with_script(self):
        """Launches Photoshop with the generated JSX script."""
        is_posix = (os.name == 'posix')
        if is_posix:
            command = ['open', '-a', self.photoshop_path, self.temp_jsx_file]
            subprocess.Popen(command)
        else:
            command = '"{0}" "{1}"'.format(self.photoshop_path, self.temp_jsx_file)
            subprocess.Popen(command, shell=True)

    def _generate_jsx(self, path_data, make_selection_only, expand_texels):
        """Builds the entire JSX script string with error handling."""
        path_array_str = "[\n"
        for i, path_info in enumerate(path_data):
            path_array_str += "    {\n"
            path_array_str += "        form: {0},\n".format(path_info['form'])
            path_array_str += "        smooth: {0},\n".format(str(path_info.get('smooth', False)).lower())
            path_array_str += "        points: [\n"
            for point in path_info['points']:
                path_array_str += "            [{0}, {1}, {2}, {3}, {4}, {5}],\n".format(
                    point[0], point[1], point[2], point[3], point[4], point[5])
            path_array_str += "        ]\n"
            path_array_str += "    }" + ("," if i < len(path_data) - 1 else "") + "\n"
        path_array_str += "];\n"

        jsx_template = """
// JSX Script generated by Maya

(function() {{
    try {{
        if (app.documents.length === 0) {{
            app.documents.add(2048, 2048, 72, "Maya Export", NewDocumentMode.RGB, DocumentFill.WHITE);
        }}

        var doc = app.activeDocument;
        var docW = Number(doc.width.as('px'));
        var docH = Number(doc.height.as('px'));

        var allPathData = {path_array_str}

        var subPathInfos = [];
        for (var i = 0; i < allPathData.length; i++) {{
            var pathInfo = allPathData[i];
            var pathPoints = [];
            for (var j = 0; j < pathInfo.points.length; j++) {{
                var p = pathInfo.points[j];
                var pointInfo = new PathPointInfo();
                pointInfo.kind = pathInfo.smooth ? PointKind.SMOOTHPOINT : PointKind.CORNERPOINT;
                pointInfo.anchor = [Number(p[0]) * docW, Number(1.0 - p[1]) * docH];
                pointInfo.leftDirection = [Number(p[2]) * docW, Number(1.0 - p[3]) * docH];
                pointInfo.rightDirection = [Number(p[4]) * docW, Number(1.0 - p[5]) * docH];
                pathPoints.push(pointInfo);
            }}

            var subPathInfo = new SubPathInfo();
            subPathInfo.operation = ShapeOperation.SHAPEXOR;
            subPathInfo.closed = (pathInfo.form !== 0);
            subPathInfo.entireSubPath = pathPoints;
            subPathInfos.push(subPathInfo);
        }}

        if (subPathInfos.length > 0) {{
            var timestamp = new Date().getTime();
            var pathItem = doc.pathItems.add("MayaSelectionPath_" + timestamp, subPathInfos);

            pathItem.makeSelection(0, false, SelectionType.REPLACE);

            var expandPixels = {expand_texels};
            if (expandPixels > 0) {{
                doc.selection.expand(expandPixels);
            }}

            if ({make_selection_only}) {{
                pathItem.remove();
            }}
        }}

    }} catch (e) {{
        alert("Photoshop Script Error:\\n" +
              "Message: " + e.message + "\\n" +
              "Line: " + e.line);
    }}
}})();
""".format(
            path_array_str=path_array_str,
            expand_texels=expand_texels,
            make_selection_only=str(make_selection_only).lower()
        )
        return jsx_template

class MayaToPhotoshopExporter(object):
    """Handles the logic of extracting and processing geometry data within Maya."""

    def __init__(self, continuous_path, expand_texels):
        self.continuous_path = continuous_path
        self.expand_texels = expand_texels

    def export_selection(self):
        """Main export method."""
        original_selection = cmds.ls(sl=True, long=True)
        if not original_selection:
            cmds.warning("No objects or components selected.")
            return None

        if cmds.filterExpand(sm=31, ex=True) or cmds.filterExpand(sm=32, ex=True):
            cmds.warning("Please select faces or polygon objects only. Vertex and Edge selections are not supported.")
            return None

        face_selection = cmds.filterExpand(sm=34, ex=True)
        if not face_selection:
            object_selection = cmds.ls(sl=True, o=True, type='transform', long=True)
            if not object_selection:
                cmds.warning("Selection is not a polygon face or object.")
                return None
            face_selection = cmds.polyListComponentConversion(object_selection, toFace=True)
            face_selection = cmds.ls(face_selection, flatten=True, long=True)

        if not face_selection:
            cmds.warning("Could not resolve selection to any polygon faces.")
            return None

        progress_window = ProgressWindow("Exporting to Photoshop")
        progress_window.set_progress(10, "Processing UV data...")

        try:
            if self.continuous_path:
                path_data = self._process_continuous(face_selection)
            else:
                path_data = self._process_discontinuous(face_selection)
        finally:
            progress_window.close()
            if original_selection:
                cmds.select(original_selection, r=True)

        return path_data

    def _get_uv_border_edges(self, faces):
        """Gets UV edges that form the boundary of the UV selection."""
        orig_sel = cmds.ls(sl=True)
        
        try:
            meshes_faces = {}
            for face in faces:
                mesh = face.split('.')[0]
                if mesh not in meshes_faces:
                    meshes_faces[mesh] = []
                meshes_faces[mesh].append(face)
            
            all_border_edges = []
            uv_positions = {}
            
            for mesh, mesh_faces in meshes_faces.items():
                all_edges = set()
                face_uv_map = {}
                
                for face in mesh_faces:
                    face_uvs = cmds.polyListComponentConversion(face, toUV=True)
                    face_uvs = cmds.ls(face_uvs, flatten=True)
                    face_uv_map[face] = face_uvs
                    
                    face_edges = cmds.polyListComponentConversion(face, toEdge=True)
                    face_edges = cmds.ls(face_edges, flatten=True)
                    all_edges.update(face_edges)
                
                all_selected_uvs = set()
                for face_uvs in face_uv_map.values():
                    all_selected_uvs.update(face_uvs)
                
                for uv in all_selected_uvs:
                    pos = cmds.polyEditUV(uv, q=True)
                    if pos and len(pos) >= 2:
                        uv_positions[uv] = self._clamp_uv(float(pos[0]), float(pos[1]))
                
                for edge in all_edges:
                    edge_faces = cmds.polyListComponentConversion(edge, toFace=True)
                    edge_faces = cmds.ls(edge_faces, flatten=True)
                    
                    selected_edge_faces = [f for f in edge_faces if f in mesh_faces]
                    
                    if len(selected_edge_faces) == 1:
                        selected_face = selected_edge_faces[0]
                        border_edge = self._extract_edge_uv_pair(edge, selected_face, face_uv_map, uv_positions)
                        if border_edge:
                            all_border_edges.append(border_edge)
                    
                    elif len(selected_edge_faces) == 2:
                        face1, face2 = selected_edge_faces[0], selected_edge_faces[1]
                        
                        edge_uv_pair1 = self._extract_edge_uv_pair(edge, face1, face_uv_map, uv_positions)
                        edge_uv_pair2 = self._extract_edge_uv_pair(edge, face2, face_uv_map, uv_positions)
                        
                        if edge_uv_pair1 and edge_uv_pair2:
                            uv1_pos1, uv1_pos2 = uv_positions[edge_uv_pair1[0]], uv_positions[edge_uv_pair1[1]]
                            uv2_pos1, uv2_pos2 = uv_positions[edge_uv_pair2[0]], uv_positions[edge_uv_pair2[1]]
                            
                            tolerance = 1e-6
                            is_seam = (
                                abs(uv1_pos1[0] - uv2_pos1[0]) > tolerance or 
                                abs(uv1_pos1[1] - uv2_pos1[1]) > tolerance or
                                abs(uv1_pos2[0] - uv2_pos2[0]) > tolerance or 
                                abs(uv1_pos2[1] - uv2_pos2[1]) > tolerance
                            )
                            
                            if is_seam:
                                all_border_edges.append(edge_uv_pair1)
                                all_border_edges.append(edge_uv_pair2)
            
            print(f"Found {len(all_border_edges)} border edges (including UV seams)")
            return all_border_edges, uv_positions
            
        finally:
            if orig_sel:
                cmds.select(orig_sel)
            else:
                cmds.select(clear=True)

    def _extract_edge_uv_pair(self, edge, face, face_uv_map, uv_positions):
        """Extract UV pair for an edge within a specific face context."""
        edge_verts = cmds.polyListComponentConversion(edge, toVertex=True)
        edge_verts = cmds.ls(edge_verts, flatten=True)
        
        if len(edge_verts) != 2:
            return None
            
        face_uvs = set(face_uv_map[face])
        edge_uv_pair = []
        
        for vert in edge_verts:
            vert_uvs = cmds.polyListComponentConversion(vert, toUV=True)
            vert_uvs = cmds.ls(vert_uvs, flatten=True)
            
            found_uv = None
            for uv in vert_uvs:
                if uv in face_uvs:
                    found_uv = uv
                    break
            
            if found_uv:
                edge_uv_pair.append(found_uv)
        
        if len(edge_uv_pair) == 2:
            uv1, uv2 = edge_uv_pair
            pos1 = uv_positions.get(uv1)
            pos2 = uv_positions.get(uv2)
            
            if pos1 and pos2 and pos1 != pos2:
                return (uv1, uv2)
        
        return None

    def _clamp_uv(self, u, v):
        u = u % 1.0
        v = v % 1.0
        if u < 0: u += 1.0
        if v < 0: v += 1.0
        return u, v

    def _process_discontinuous(self, faces):
        """Process each border edge as a separate, two-point path."""
        border_edges, uv_positions = self._get_uv_border_edges(faces)
        if not border_edges:
            return []

        all_paths = []
        for uv1, uv2 in border_edges:
            if uv1 in uv_positions and uv2 in uv_positions:
                pos1, pos2 = uv_positions[uv1], uv_positions[uv2]
                all_paths.append({
                    'form': 0,
                    'smooth': False,
                    'points': [
                        [pos1[0], pos1[1], pos1[0], pos1[1], pos1[0], pos1[1]],
                        [pos2[0], pos2[1], pos2[0], pos2[1], pos2[0], pos2[1]]
                    ]
                })
        return all_paths

    def _process_continuous(self, faces):
        """Process UV shell boundaries into continuous paths."""
        border_edges, uv_positions = self._get_uv_border_edges(faces)
        if not border_edges:
            return []
            
        edge_graph = {}
        for i, (uv1, uv2) in enumerate(border_edges):
            edge_graph.setdefault(uv1, []).append((uv2, i))
            edge_graph.setdefault(uv2, []).append((uv1, i))

        def trace_component_boundary(start_uv, visited_edges):
            """Trace boundary from a starting UV point."""
            path = [start_uv]
            current_uv = start_uv
            
            while True:
                if current_uv not in edge_graph:
                    break
                
                candidates = [(next_uv, edge_idx) for next_uv, edge_idx in edge_graph[current_uv]
                             if edge_idx not in visited_edges]
                
                if not candidates:
                    break
                
                next_uv, edge_idx = candidates[0]
                visited_edges.add(edge_idx)
                
                if next_uv == start_uv and len(path) > 2:
                    break
                
                if next_uv in path:
                    break
                
                path.append(next_uv)
                current_uv = next_uv
            
            return path

        all_paths = []
        visited_edges = set()
        processed_uvs = set()
        
        degree_map = {uv: len(connections) for uv, connections in edge_graph.items()}
        start_candidates = sorted(edge_graph.keys(), key=lambda uv: degree_map[uv])
        
        for start_uv in start_candidates:
            if start_uv in processed_uvs:
                continue
                
            path = trace_component_boundary(start_uv, visited_edges)
            
            if len(path) >= 2:
                processed_uvs.update(path)
                
                path_points = []
                for uv in path:
                    if uv in uv_positions:
                        coords = uv_positions[uv]
                        path_points.append([coords[0], coords[1], coords[0], coords[1], coords[0], coords[1]])
                
                if len(path_points) >= 2:
                    is_closed = (len(path) > 2 and path[-1] in edge_graph and 
                               any(next_uv == path[0] for next_uv, _ in edge_graph[path[-1]]))
                    
                    all_paths.append({
                        'form': 1 if is_closed else 0,
                        'smooth': False,
                        'points': path_points
                    })

        print("Generated {0} UV boundary paths".format(len(all_paths)))
        return all_paths


class ProgressWindow(object):
    """A simple, self-contained progress window class."""

    def __init__(self, title="Progress..."):
        self.window_name = "newfunction_progressWindow"
        if cmds.window(self.window_name, exists=True):
            cmds.deleteUI(self.window_name)
        
        self.window = cmds.window(self.window_name, title=title, sizeable=False)
        cmds.columnLayout(adjustableColumn=True)
        self.text_label = cmds.text(label="Initializing...", align='center')
        self.progress_bar = cmds.progressBar(maxValue=100, width=400, isInterruptable=True)
        cmds.showWindow(self.window)

    def set_progress(self, value, message=None):
        if not cmds.window(self.window_name, exists=True):
            return
        if cmds.progressBar(self.progress_bar, query=True, isCancelled=True):
            raise RuntimeError("Operation cancelled by user.")
        if message:
            cmds.text(self.text_label, edit=True, label=message)
        cmds.progressBar(self.progress_bar, edit=True, progress=value)

    def close(self):
        if cmds.window(self.window_name, exists=True):
            cmds.deleteUI(self.window_name)

class MayaToPhotoshopUI(object):
    """A class to create and manage the script's UI."""
    
    WINDOW_NAME = "newfunction_mainWindow"
    WINDOW_TITLE = "Export to Photoshop"

    def __init__(self):
        if cmds.window(self.WINDOW_NAME, exists=True):
            cmds.deleteUI(self.WINDOW_NAME, window=True)

        self.window = cmds.window(self.WINDOW_NAME, title=self.WINDOW_TITLE, 
                                 widthHeight=(300, 140), sizeable=False, maximizeButton=False)
        self._build_ui()
        cmds.showWindow(self.window)

    def _build_ui(self):
        """Creates the UI layout and controls."""
        cmds.columnLayout(adjustableColumn=True, rowSpacing=3, parent=self.window)
        
        cmds.rowLayout(numberOfColumns=3, adjustableColumn=2, columnWidth3=(60, 200, 30))
        cmds.text(label="Photoshop:")
        self.path_field = cmds.textField(text=self._load_setting("photoshop_path", ""))
        cmds.button(label="...", command=self._browse_for_photoshop)
        cmds.setParent('..')
        
        cmds.separator(height=3)

        cmds.rowLayout(numberOfColumns=3, adjustableColumn=1, columnWidth3=(100, 50, 30))
        self.enable_expand_cb = cmds.checkBox(
            label="Expand Selection", 
            value=self._load_setting("enable_expand", False),
            changeCommand=self._on_expand_changed
        )
        cmds.text(label="px:")
        self.expand_field = cmds.intField(
            value=self._load_setting("expand_texels", 4), 
            minValue=0, maxValue=100,
            enable=self._load_setting("enable_expand", False)
        )
        cmds.setParent('..')

        cmds.separator(height=3)

        self.continuous_cb = cmds.checkBox(
            label="Continuous Path", 
            value=self._load_setting("continuous_path", True)
        )
        
        self.selection_only_cb = cmds.checkBox(
            label="Selection Only", 
            value=self._load_setting("selection_only", True)
        )

        cmds.separator(height=5)
        cmds.button(label="Export to Photoshop", height=25, command=self._export)

    def _load_setting(self, key, default):
        """Load setting with simplified key names."""
        full_key = CONFIG_KEYS.get(key, "newfunction_" + key)
        if not cmds.optionVar(exists=full_key):
            return default
        return cmds.optionVar(query=full_key) if isinstance(default, str) else bool(cmds.optionVar(query=full_key))

    def _save_setting(self, key, value):
        """Save setting with simplified key names."""
        full_key = CONFIG_KEYS.get(key, "newfunction_" + key)
        if isinstance(value, bool):
            cmds.optionVar(intValue=(full_key, int(value)))
        else:
            cmds.optionVar(stringValue=(full_key, value))

    def _on_expand_changed(self, value):
        """Handle expand checkbox change."""
        self._save_setting("enable_expand", value)
        cmds.intField(self.expand_field, edit=True, enable=value)

    def _browse_for_photoshop(self, *args):
        """Browse for Photoshop executable."""
        file_filter = "*.exe" if os.name != 'posix' else "*.app"
        file_path = cmds.fileDialog2(
            caption="Browse for Photoshop",
            fileFilter=file_filter,
            fileMode=1
        )
        
        if file_path:
            cmds.textField(self.path_field, edit=True, text=file_path[0])
            self._save_setting("photoshop_path", file_path[0])

    def _export(self, *args):
        """Main export function."""
        photoshop_path = cmds.textField(self.path_field, query=True, text=True)
        if not photoshop_path or not os.path.exists(photoshop_path):
            cmds.warning("Please set a valid Photoshop path.")
            return

        continuous_path = cmds.checkBox(self.continuous_cb, query=True, value=True)
        enable_expand = cmds.checkBox(self.enable_expand_cb, query=True, value=True)
        expand_texels = cmds.intField(self.expand_field, query=True, value=True) if enable_expand else 0
        selection_only = cmds.checkBox(self.selection_only_cb, query=True, value=True)
        
        self._save_setting("continuous_path", continuous_path)
        self._save_setting("enable_expand", enable_expand)
        self._save_setting("expand_texels", expand_texels)
        self._save_setting("selection_only", selection_only)
        
        try:
            exporter = MayaToPhotoshopExporter(continuous_path, expand_texels)
            path_data = exporter.export_selection()

            if path_data:
                communicator = PhotoshopCommunicator(photoshop_path)
                communicator.execute(path_data, selection_only, expand_texels)
                print("Export sent to Photoshop successfully.")
            else:
                cmds.warning("No valid path data generated.")

        except Exception as e:
            cmds.error("Export failed: {0}".format(str(e)))

def _find_photoshop_path():
    """Attempts to automatically find the Photoshop application path."""
    if sys.platform == "darwin":
        try:
            apps_dir = "/Applications"
            for item in os.listdir(apps_dir):
                if "photoshop" in item.lower() and item.endswith(".app"):
                    return os.path.join(apps_dir, item)
            path = subprocess.check_output(['mdfind', 'kMDItemKind=="Application" && kMDItemDisplayName=="*Photoshop*"']).decode('utf-8').split('\n')[0]
            if path:
                return path
        except (subprocess.CalledProcessError, OSError, IndexError):
            pass
    elif sys.platform == "win32":
        try:
            import _winreg as winreg
            for version in range(200, 0, -1):
                try:
                    key_path = "SOFTWARE\\Adobe\\Photoshop\\{0}.0".format(version)
                    with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, key_path) as key:
                        app_path = winreg.QueryValueEx(key, "ApplicationPath")[0]
                        if app_path:
                            return os.path.join(app_path, "Photoshop.exe")
                except WindowsError:
                    continue
        except (ImportError, OSError):
            pass
    return ""

def run():
    """Main entry point to launch the UI."""
    if not cmds.optionVar(exists=CONFIG_KEYS["photoshop_path"]):
        ps_path = _find_photoshop_path()
        if ps_path:
            cmds.optionVar(stringValue=(CONFIG_KEYS["photoshop_path"], ps_path))
            print("Auto-detected Photoshop at: {0}".format(ps_path))
    
    MayaToPhotoshopUI()
